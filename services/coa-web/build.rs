//! Builds the web service from the desktop Manager's own command code.
//!
//! The desktop app's commands (`src-tauri/src`) are plain Rust functions marked `#[tauri::command]`; very little of them
//! depends on Tauri itself. This script reads those files, removes what only a desktop window needs (the `run()` that
//! builds the window, tray and plugins), points their `tauri::` paths at the small stand-in in `src/shim.rs`, and writes
//! them as one module into `$OUT_DIR/desktop.rs`. For every command the desktop app registers it also writes the HTTP
//! side: reading each argument from the JSON body under the name the interface sends (camelCase, as Tauri does) and
//! turning the result into JSON. A command added or changed upstream is therefore served by the web version as soon as
//! it builds, with the desktop's own code.

use std::collections::{BTreeMap, HashSet};
use std::fs;
use std::path::{Path, PathBuf};

use quote::{format_ident, quote};
use syn::visit_mut::{self, VisitMut};
use syn::{Attribute, FnArg, Item, ItemFn, Pat, ReturnType, Type};

/// Desktop-only items that are left out: they build the window, the tray and the plugins.
const DROP_FNS: &[&str] = &["run", "show_main_window"];

/// Functions whose body the web version replaces, as (module, function, replacement body).
const OVERRIDES: &[(&str, &str, &str)] = &[
    // The web service may be told which key the Linux package is signed with (COA_TRUSTED_KEY), also in a release
    // build: whoever runs it can build and sign the package themselves. The desktop allows that only in debug builds.
    ("docker_install", "trusted_key", "{ crate::overrides::trusted_key() }"),
];

struct Command {
    module: Vec<String>,
    name: String,
    func: ItemFn,
    snake_case: bool,
}

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let desktop = manifest.join("../../src-tauri/src");
    let lib = desktop.join("lib.rs");
    println!("cargo:rerun-if-changed={}", desktop.display());
    println!("cargo:rerun-if-changed=build.rs");

    let mut commands = Vec::new();
    let items = load_module(&lib, &desktop, &[], &mut commands);
    let registered = registered_commands(&fs::read_to_string(&lib).unwrap());

    let mut by_module: BTreeMap<Vec<String>, Vec<&Command>> = BTreeMap::new();
    for c in &commands {
        let path = c.module.iter().cloned().chain([c.name.clone()]).collect::<Vec<_>>().join("::");
        if registered.contains(&path) {
            by_module.entry(c.module.clone()).or_default().push(c);
        }
    }
    let missing: Vec<_> = registered
        .iter()
        .filter(|p| !commands.iter().any(|c| c.module.iter().cloned().chain([c.name.clone()]).collect::<Vec<_>>().join("::") == **p))
        .collect();
    if !missing.is_empty() {
        panic!("registered desktop commands not found in the sources: {missing:?}");
    }

    let mut file = syn::File { shebang: None, attrs: vec![], items };
    add_dispatch(&mut file.items, &[], &by_module);
    file.items.push(make_state(&fs::read_to_string(&lib).unwrap()));
    file.items.push(syn::parse2(quote! {
        include!(concat!(env!("CARGO_MANIFEST_DIR"), "/src/desktop_glue.rs"));
    }).unwrap());

    let names: Vec<String> = by_module.values().flatten().map(|c| c.name.clone()).collect();
    let modules: Vec<_> = by_module
        .keys()
        .map(|m| {
            let segs = m.iter().map(|s| format_ident!("{s}"));
            quote! { if let Some(r) = self::#(#segs::)*__web_dispatch(st, app, name, args).await { return Some(r); } }
        })
        .collect();
    file.items.push(syn::parse2(quote! {
        /// Every command the desktop app registers, as the interface names it.
        pub const COMMANDS: &[&str] = &[#(#names),*];
    }).unwrap());
    file.items.push(syn::parse2(quote! {
        /// Run one command: `None` when the desktop app has no command of that name.
        pub async fn dispatch(
            st: &std::sync::Arc<AppState>,
            app: &crate::shim::tauri::AppHandle,
            name: &str,
            args: &serde_json::Value,
        ) -> Option<std::result::Result<serde_json::Value, serde_json::Value>> {
            #(#modules)*
            None
        }
    }).unwrap());

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("desktop.rs");
    let text = prettyplease::unparse(&file);
    fs::write(&out, format!("// Generated by build.rs from src-tauri/src: do not edit.\n{text}")).unwrap();
}

/// The `generate_handler![...]` list of the desktop app's `run()`: the commands the interface can call.
fn registered_commands(lib: &str) -> HashSet<String> {
    let start = lib.find("generate_handler![").expect("generate_handler! not found") + "generate_handler![".len();
    let end = start + lib[start..].find(']').unwrap();
    lib[start..end]
        .split(',')
        .map(|s| s.split_whitespace().collect::<String>())
        .filter(|s| !s.is_empty())
        .collect()
}

/// Read one source file of the desktop app and prepare its items for the web build.
fn load_module(path: &Path, dir: &Path, module: &[String], commands: &mut Vec<Command>) -> Vec<Item> {
    let source = fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let file = syn::parse_file(&source).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let mut items = vec![
        syn::parse2(quote! { #[allow(unused_imports)] use crate::shim::{tauri, tauri_plugin_opener}; }).unwrap(),
    ];
    for mut item in file.items {
        // The web service holds the desktop state next to its own.
        if let Item::Struct(s) = &mut item {
            if module.is_empty() && s.ident == "AppState" {
                s.vis = syn::parse_quote!(pub(crate));
            }
        }
        if is_test(item_attrs(&item)) {
            continue;
        }
        match item {
            Item::Fn(mut f) => {
                let name = f.sig.ident.to_string();
                if module.is_empty() && DROP_FNS.contains(&name.as_str()) {
                    continue;
                }
                let module_name = module.join("::");
                if let Some((_, _, body)) = OVERRIDES.iter().find(|(m, n, _)| *m == module_name && *n == name) {
                    f.block = Box::new(syn::parse_str(body).unwrap());
                }
                if let Some(snake_case) = take_command_attr(&mut f.attrs) {
                    commands.push(Command { module: module.to_vec(), name, func: f.clone(), snake_case });
                }
                items.push(Item::Fn(f));
            }
            Item::Mod(mut m) if m.content.is_none() => {
                let name = m.ident.to_string();
                let child = dir.join(format!("{name}.rs"));
                let mut path = module.to_vec();
                path.push(name);
                let inner = load_module(&child, dir, &path, commands);
                m.content = Some((Default::default(), inner));
                m.semi = None;
                items.push(Item::Mod(m));
            }
            other => items.push(other),
        }
    }
    // Child modules were rewritten when they were loaded; their paths already start `crate::desktop`.
    let mut paths = CratePaths;
    for item in &mut items {
        if !matches!(item, Item::Mod(_)) {
            paths.visit_item_mut(item);
        }
    }
    items
}

/// `make_state()`: the statements of the desktop app's `.setup(|app| { ... })` up to `app.manage(AppState { .. })`,
/// returning that state. The window and tray part that follows is left out.
fn make_state(lib: &str) -> Item {
    struct FindSetup(Option<syn::Block>);
    impl<'a> syn::visit::Visit<'a> for FindSetup {
        fn visit_expr_method_call(&mut self, m: &'a syn::ExprMethodCall) {
            if m.method == "setup" {
                if let Some(syn::Expr::Closure(c)) = m.args.first() {
                    if let syn::Expr::Block(b) = &*c.body {
                        self.0 = Some(b.block.clone());
                    }
                }
            }
            syn::visit::visit_expr_method_call(self, m);
        }
    }
    let file = syn::parse_file(lib).unwrap();
    let run = file
        .items
        .iter()
        .find_map(|i| match i {
            Item::Fn(f) if f.sig.ident == "run" => Some(f),
            _ => None,
        })
        .expect("run() not found");
    let mut find = FindSetup(None);
    syn::visit::Visit::visit_item_fn(&mut find, run);
    let block = find.0.expect(".setup(|app| { .. }) not found in run()");
    let mut stmts = Vec::new();
    let mut state = None;
    for stmt in block.stmts {
        if let syn::Stmt::Expr(syn::Expr::MethodCall(m), _) = &stmt {
            if m.method == "manage" {
                state = m.args.first().cloned();
                break;
            }
        }
        stmts.push(stmt);
    }
    let state = state.expect("app.manage(AppState { .. }) not found in the setup");
    let mut item: Item = syn::parse2(quote! {
        /// The desktop app's state, built exactly as its window setup builds it.
        pub(crate) fn make_state() -> AppState {
            #(#stmts)*
            #state
        }
    })
    .unwrap();
    CratePaths.visit_item_mut(&mut item);
    item
}

fn item_attrs(item: &Item) -> &[Attribute] {
    match item {
        Item::Fn(i) => &i.attrs,
        Item::Mod(i) => &i.attrs,
        Item::Use(i) => &i.attrs,
        Item::Impl(i) => &i.attrs,
        Item::Struct(i) => &i.attrs,
        Item::Enum(i) => &i.attrs,
        Item::Const(i) => &i.attrs,
        Item::Static(i) => &i.attrs,
        _ => &[],
    }
}

/// `#[cfg(test)]`, `#[cfg(all(test, ..))]`: the desktop app's own tests stay in the desktop build.
fn is_test(attrs: &[Attribute]) -> bool {
    attrs.iter().any(|a| {
        a.path().is_ident("cfg")
            && a.meta.require_list().is_ok_and(|l| {
                let t = l.tokens.to_string();
                t == "test" || t.starts_with("all (test")
            })
    })
}

/// Remove `#[tauri::command]`; `Some(snake_case)` when the function had it.
fn take_command_attr(attrs: &mut Vec<Attribute>) -> Option<bool> {
    let pos = attrs.iter().position(|a| {
        let p = a.path();
        p.segments.len() == 2 && p.segments[0].ident == "tauri" && p.segments[1].ident == "command"
    })?;
    let attr = attrs.remove(pos);
    let tokens = attr.meta.require_list().map(|l| l.tokens.to_string()).unwrap_or_default();
    Some(tokens.contains("rename_all") && tokens.contains("snake_case"))
}

/// The desktop code lives under `crate::desktop` here: its `crate::` paths are moved with it.
struct CratePaths;

/// Top-level modules of the web service the desktop code is pointed at (shim, overrides) or that it now lives in.
const WEB_MODULES: &[&str] = &["shim", "desktop", "overrides", "web_args"];

impl VisitMut for CratePaths {
    /// `pub(crate)` keeps meaning the whole service.
    fn visit_visibility_mut(&mut self, _: &mut syn::Visibility) {}

    fn visit_path_mut(&mut self, p: &mut syn::Path) {
        let web_own = p.segments.iter().nth(1).is_some_and(|s| WEB_MODULES.iter().any(|m| s.ident == m));
        if !web_own && p.segments.first().is_some_and(|s| s.ident == "crate") {
            p.segments.insert(1, syn::PathSegment::from(format_ident!("desktop")));
        }
        visit_mut::visit_path_mut(self, p);
    }

    fn visit_use_tree_mut(&mut self, t: &mut syn::UseTree) {
        if let syn::UseTree::Path(p) = t {
            let web_own = matches!(&*p.tree, syn::UseTree::Path(n) if WEB_MODULES.iter().any(|m| n.ident == m));
            if p.ident == "crate" && !web_own {
                let rest = (*p.tree).clone();
                p.tree = Box::new(syn::UseTree::Path(syn::UsePath {
                    ident: format_ident!("desktop"),
                    colon2_token: Default::default(),
                    tree: Box::new(rest),
                }));
                return;
            }
        }
        visit_mut::visit_use_tree_mut(self, t);
    }
}

/// Add `__web_dispatch` to every module that holds commands (recursively into inline modules).
fn add_dispatch(items: &mut Vec<Item>, module: &[String], by_module: &BTreeMap<Vec<String>, Vec<&Command>>) {
    for item in items.iter_mut() {
        if let Item::Mod(m) = item {
            if let Some((_, inner)) = &mut m.content {
                let mut path = module.to_vec();
                path.push(m.ident.to_string());
                add_dispatch(inner, &path, by_module);
            }
        }
    }
    let Some(cmds) = by_module.get(module) else { return };
    let arms = cmds.iter().map(|c| arm(c));
    items.push(
        syn::parse2(quote! {
            pub(crate) async fn __web_dispatch(
                __st: &std::sync::Arc<crate::desktop::AppState>,
                __app: &crate::shim::tauri::AppHandle,
                __name: &str,
                __args: &serde_json::Value,
            ) -> Option<std::result::Result<serde_json::Value, serde_json::Value>> {
                match __name {
                    #(#arms)*
                    _ => None,
                }
            }
        })
        .unwrap(),
    );
}

fn arm(c: &Command) -> proc_macro2::TokenStream {
    let name = &c.name;
    let ident = format_ident!("{}", c.name);
    let mut lets = Vec::new();
    let mut call = Vec::new();
    for (i, input) in c.func.sig.inputs.iter().enumerate() {
        let FnArg::Typed(pt) = input else { panic!("{name}: a command cannot take self") };
        let ty = &*pt.ty;
        let var = format_ident!("__a{i}");
        match last_ident(ty).as_deref() {
            Some("State") => call.push(quote! { crate::shim::tauri::State::new(&**__st) }),
            Some("AppHandle") => call.push(quote! { __app.clone() }),
            Some("Window") | Some("WebviewWindow") => {
                return quote! { #name => Some(Err(serde_json::json!("This command needs the desktop window."))), };
            }
            _ => {
                let Pat::Ident(pi) = &*pt.pat else { panic!("{name}: unsupported argument pattern") };
                let rust = pi.ident.to_string();
                let key = if c.snake_case { rust.clone() } else { camel(&rust) };
                lets.push(quote! { let #var: #ty = crate::web_args::arg(__args, #key)?; });
                call.push(quote! { #var });
            }
        }
    }
    let invoke = if c.func.sig.asyncness.is_some() {
        quote! { #ident(#(#call),*).await }
    } else {
        quote! { #ident(#(#call),*) }
    };
    let finish = match &c.func.sig.output {
        ReturnType::Type(_, t) if last_ident(t).as_deref() == Some("Result") => quote! { crate::web_args::res(__r) },
        _ => quote! { crate::web_args::ok(__r) },
    };
    quote! {
        #name => Some(async {
            #(#lets)*
            let __r = #invoke;
            #finish
        }.await),
    }
}

fn last_ident(ty: &Type) -> Option<String> {
    match ty {
        Type::Path(p) => p.path.segments.last().map(|s| s.ident.to_string()),
        Type::Reference(r) => last_ident(&r.elem),
        _ => None,
    }
}

/// Tauri's default: `snake_case` Rust arguments are `camelCase` keys in the interface's call.
fn camel(s: &str) -> String {
    let mut out = String::new();
    let mut up = false;
    for ch in s.chars() {
        if ch == '_' {
            up = !out.is_empty();
        } else if up {
            out.extend(ch.to_uppercase());
            up = false;
        } else {
            out.push(ch);
        }
    }
    out
}
